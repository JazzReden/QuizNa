import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const directory = new URL('supabase/migrations/', root);
const files = (await readdir(directory)).filter(f => /^\d+_.*\.sql$/.test(f)).sort((a,b) => Number(a.split('_')[0])-Number(b.split('_')[0]));
const parts = [];
for (const file of files) {
  const source = await readFile(new URL(file, directory), 'utf8');
  parts.push(`-- SOURCE: ${file}\n${source.replace(/^\s*(?:BEGIN|COMMIT);\s*$/gm, '')}`);
}
const sql = `-- GENERATED by npm run deploy:database; do not edit directly.\n-- FRESH SUPABASE PROJECT ONLY. No seed accounts, questions, or scores.\nBEGIN;\nDO $$ BEGIN\n IF to_regclass('public.profiles') IS NOT NULL OR to_regclass('public.quizzes') IS NOT NULL THEN\n  RAISE EXCEPTION 'QuizNa tables already exist. Apply individual pending migrations instead.';\n END IF;\nEND $$;\n${parts.join('\n\n')}\nCOMMIT;\n`;
await mkdir(new URL('deploy/', root), {recursive:true});
await writeFile(new URL('deploy/supabase-bootstrap.sql', root), sql);
console.log(`Prepared ${files.length} ordered migrations in deploy/supabase-bootstrap.sql; no remote database was modified.`);
